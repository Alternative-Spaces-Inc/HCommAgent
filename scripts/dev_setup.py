#!/usr/bin/env python3
"""Create or serve an isolated loopback development environment."""
import argparse
import os
from pathlib import Path
import secrets
import subprocess
import sys
import tempfile

from dotenv import dotenv_values

ROOT = Path(__file__).resolve().parents[1]
CONFIG = ROOT / ".env.development"
DATABASE = ROOT / "api" / "hca_development.db"
DATABASE_URL = "sqlite:///" + str(DATABASE)


def isolated_environment(values):
    env = {k: v for k, v in os.environ.items() if not k.startswith(("HCA_", "WEBHOOK_", "SWEEP_", "K_"))
           and k not in {"DATABASE_URL", "HTTP_PROXY", "HTTPS_PROXY", "ALL_PROXY", "NO_PROXY"}}
    return env | values | {"NO_PROXY": "127.0.0.1,localhost,::1"}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--force", action="store_true", help="replace only this disposable development configuration")
    parser.add_argument("--serve", action="store_true", help="validate local config, migrate and serve on loopback port 8000")
    args = parser.parse_args()
    if CONFIG.exists() and not args.force:
        if not args.serve:
            raise SystemExit(".env.development already exists; use --serve, or --force to explicitly regenerate disposable credentials")
        values = {k: v for k, v in dotenv_values(CONFIG).items() if v is not None}
    else:
        if args.force and DATABASE.exists():
            raise SystemExit("Stop the local API and remove its disposable database before replacing credentials")
        values = {"HCA_ENV": "development", "DATABASE_URL": DATABASE_URL,
                  "HCA_ADMIN_TOKEN": secrets.token_urlsafe(32), "SWEEP_TRIGGER_TOKEN": secrets.token_urlsafe(32),
                  "HCA_API_KEY_PEPPER": secrets.token_urlsafe(32), "HCA_REQUIRE_GOOGLE_LINK": "0",
                  "HCA_WEBHOOK_ALLOW_INSECURE": "1"}
        fd, temporary = tempfile.mkstemp(prefix=".env-development-", dir=ROOT)
        try:
            with os.fdopen(fd, "w") as file:
                file.write("# Disposable loopback development only; never commit this file.\n")
                file.write("\n".join(f"{k}='{v}'" for k, v in values.items()) + "\n")
            os.replace(temporary, CONFIG)
        finally:
            Path(temporary).unlink(missing_ok=True)
    if (values.get("HCA_ENV") != "development" or values.get("DATABASE_URL") != DATABASE_URL
            or values.get("HCA_REQUIRE_GOOGLE_LINK") != "0" or values.get("HCA_WEBHOOK_ALLOW_INSECURE") != "1"):
        raise SystemExit("Refusing non-local configuration; use only the generated disposable development environment")
    for name in ("HCA_ADMIN_TOKEN", "SWEEP_TRIGGER_TOKEN", "HCA_API_KEY_PEPPER"):
        if len(values.get(name, "")) < 32:
            raise SystemExit("Development credentials must be generated by this script")
    env = isolated_environment(values)
    subprocess.run([sys.executable, "-m", "alembic", "upgrade", "head"], cwd=ROOT / "api", env=env, check=True)
    print("Disposable local database ready; private configuration is .env.development (values withheld).", flush=True)
    if args.serve:
        try:
            subprocess.run([sys.executable, "-m", "uvicorn", "app.main:app", "--host", "127.0.0.1", "--port", "8000"],
                           cwd=ROOT / "api", env=env, check=True)
        except KeyboardInterrupt:
            pass
    else:
        print("Start the loopback API: python scripts/dev_setup.py --serve")
    return 0


if __name__ == "__main__":
    sys.exit(main())
